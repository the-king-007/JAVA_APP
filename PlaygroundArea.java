public class PlaygroundArea {
    public static void main(String[] args) {
        double length = 105.5; 
        double breadth = 68.0; 

        double area = length * breadth;

        System.out.println("--- PE Department Ground Marking ---");
        System.out.println("Length of playground  : " + length + " meters");
        System.out.println("Breadth of playground : " + breadth + " meters");
        System.out.println("Calculated Area       : " + area + " sq. meters");
    }
}